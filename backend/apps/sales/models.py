from decimal import Decimal
from django.db import models
from django.conf import settings
from common.models.base import TenantScopedModel, UUIDBaseModel, TimestampedModel


class Customer(TenantScopedModel):
    name = models.CharField(max_length=150)
    phone = models.CharField(max_length=32, blank=True, db_index=True)
    email = models.EmailField(blank=True)
    tax_number = models.CharField(max_length=50, blank=True, help_text="PAN/VAT")
    address = models.TextField(blank=True)
    credit_limit = models.DecimalField(max_digits=12, decimal_places=2, default=Decimal("0.00"))
    current_credit = models.DecimalField(max_digits=12, decimal_places=2, default=Decimal("0.00"))
    loyalty_points = models.IntegerField(default=0)
    is_active = models.BooleanField(default=True)

    class Meta:
        db_table = "customers"
        unique_together = ("organization", "phone")
        ordering = ["name"]

    def __str__(self):
        return f"{self.name} ({self.phone or 'No phone'})"


class InvoiceSequence(TenantScopedModel):
    """
    Guarantees gapless or monotonically increasing invoice numbers per branch/fiscal year.
    Crucial for Nepal IRD (Inland Revenue Department) certified e-billing requirements.
    """
    branch = models.ForeignKey("branches.Branch", on_delete=models.CASCADE)
    fiscal_year = models.CharField(max_length=20, help_text="e.g. 2083/084 or 2026/2027")
    prefix = models.CharField(max_length=10, default="INV")
    next_number = models.PositiveIntegerField(default=1)

    class Meta:
        db_table = "invoice_sequences"
        unique_together = ("organization", "branch", "fiscal_year")

    @classmethod
    def get_next_invoice_number(cls, organization, branch, fiscal_year="2026/27", prefix="INV"):
        from django.db import transaction
        with transaction.atomic():
            seq, _ = cls.objects.select_for_update().get_or_create(
                organization=organization,
                branch=branch,
                fiscal_year=fiscal_year,
                defaults={"prefix": prefix, "next_number": 1}
            )
            num = seq.next_number
            seq.next_number += 1
            seq.save(update_fields=["next_number", "updated_at"])
            return f"{seq.prefix}-{branch.code}-{fiscal_year.replace('/', '')}-{num:06d}"


class Sale(TenantScopedModel):
    STATUS_CHOICES = [
        ("COMPLETED", "Completed"),
        ("REFUNDED", "Refunded"),
        ("PARTIALLY_REFUNDED", "Partially Refunded"),
        ("VOID", "Voided / Cancelled"),
    ]

    branch = models.ForeignKey("branches.Branch", on_delete=models.CASCADE, related_name="sales")
    terminal = models.ForeignKey("pos.PosTerminal", on_delete=models.SET_NULL, null=True, blank=True, related_name="sales")
    cashier = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.SET_NULL, null=True, blank=True, related_name="sales_recorded")
    customer = models.ForeignKey(Customer, on_delete=models.SET_NULL, null=True, blank=True, related_name="purchases")

    invoice_number = models.CharField(max_length=100, db_index=True)
    client_transaction_id = models.CharField(
        max_length=120, db_index=True,
        help_text="Idempotency key generated by offline POS terminal to prevent duplicate billing"
    )
    status = models.CharField(max_length=25, choices=STATUS_CHOICES, default="COMPLETED")

    subtotal = models.DecimalField(max_digits=14, decimal_places=2, default=Decimal("0.00"))
    discount_amount = models.DecimalField(max_digits=14, decimal_places=2, default=Decimal("0.00"))
    tax_amount = models.DecimalField(max_digits=14, decimal_places=2, default=Decimal("0.00"))
    total_amount = models.DecimalField(max_digits=14, decimal_places=2, default=Decimal("0.00"))
    paid_amount = models.DecimalField(max_digits=14, decimal_places=2, default=Decimal("0.00"))

    currency = models.CharField(max_length=3, default="NPR")
    notes = models.TextField(blank=True)
    synced_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        db_table = "sales"
        unique_together = ("organization", "client_transaction_id")
        ordering = ["-created_at"]

    def __str__(self):
        return f"Invoice {self.invoice_number} ({self.total_amount} {self.currency})"


class SaleItem(UUIDBaseModel, TimestampedModel):
    sale = models.ForeignKey(Sale, on_delete=models.CASCADE, related_name="items")
    variant = models.ForeignKey("catalog.ProductVariant", on_delete=models.PROTECT, related_name="sale_items")
    quantity = models.DecimalField(max_digits=12, decimal_places=3)
    unit_price = models.DecimalField(max_digits=12, decimal_places=2)
    cost_price = models.DecimalField(max_digits=12, decimal_places=2, default=Decimal("0.00"))
    discount_amount = models.DecimalField(max_digits=12, decimal_places=2, default=Decimal("0.00"))
    tax_rate = models.DecimalField(max_digits=5, decimal_places=2, default=Decimal("13.00"))
    tax_amount = models.DecimalField(max_digits=12, decimal_places=2, default=Decimal("0.00"))
    subtotal = models.DecimalField(max_digits=14, decimal_places=2)

    class Meta:
        db_table = "sale_items"

    def __str__(self):
        return f"{self.variant.sku} x {self.quantity} @ {self.unit_price}"


